# 토큰과 교집합을 구해서 모호함을 없앤다.
GU_SI_TO_SIDO: dict[str, list[str]] = {}


def _register(sido: str, names: list[str]) -> None:
    for name in names:
        GU_SI_TO_SIDO.setdefault(name, []).append(sido)


